#!/usr/bin/env node
/* eslint-disable no-console */
// Writes app/lib/sky/fontCoverage.ts: the code points both EB Garamond faces
// can print, as sorted inclusive ranges. validateSkyParams() rejects text
// outside these ranges so the preview and the print file always agree.
//
//   node scripts/build-font-coverage.mjs
import fontkit from '@pdf-lib/fontkit';
import {readFileSync, writeFileSync} from 'node:fs';

const faces = ['Regular', 'Italic'].map((f) =>
  fontkit.create(readFileSync(`public/fonts/EBGaramond-${f}.ttf`)),
);
const [first, ...rest] = faces.map((f) => new Set(f.characterSet));
const shared = [...first].filter((cp) => rest.every((s) => s.has(cp))).sort((a, b) => a - b);

const ranges = [];
for (const cp of shared) {
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) last[1] = cp;
  else ranges.push([cp, cp]);
}

const body = `// Generated by scripts/build-font-coverage.mjs — do not edit.
// Inclusive Unicode code point ranges printable by both EB Garamond faces
// (${shared.length} code points, ${ranges.length} ranges).
export const FONT_COVERAGE_RANGES: ReadonlyArray<readonly [number, number]> = [
${ranges.map(([a, b]) => `  [${a}, ${b}],`).join('\n')}
];
`;
writeFileSync('app/lib/sky/fontCoverage.ts', body);
console.log(`font coverage: ${shared.length} code points in ${ranges.length} ranges`);
/* eslint-enable no-console */
