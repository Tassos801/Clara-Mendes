#!/usr/bin/env node
/* eslint-disable no-console */
// Writes app/lib/sky/labelMetrics.ts: EB Garamond Regular advance widths, in
// em, for every character a constellation label can contain (the uppercased
// IAU names in app/data/sky/constellation-names.json, plus A–Z and space).
// placeLabels() spaces labels with these, because the scene runs in the
// browser and the Oxygen worker and cannot load the font itself.
//
//   node scripts/build-sky-label-metrics.mjs
import fontkit from '@pdf-lib/fontkit';
import {readFileSync, writeFileSync} from 'node:fs';

const font = fontkit.create(
  readFileSync('public/fonts/EBGaramond-Regular.ttf'),
);
const names = JSON.parse(
  readFileSync('app/data/sky/constellation-names.json', 'utf8'),
).data.map((row) => row[1].toUpperCase());

const chars = [
  ...new Set([...' ABCDEFGHIJKLMNOPQRSTUVWXYZ', ...names.join('')]),
].sort((a, b) => a.codePointAt(0) - b.codePointAt(0));

const entries = chars.map((ch) => {
  if (!font.hasGlyphForCodePoint(ch.codePointAt(0))) {
    throw new Error(
      `EB Garamond Regular has no glyph for ${JSON.stringify(ch)}`,
    );
  }
  // pdf.server.ts drawTracked() draws labels one glyph at a time, so a
  // single-character layout's advance is exactly what the print uses.
  const em = font.layout(ch).advanceWidth / font.unitsPerEm;
  return [ch, Math.round(em * 1000) / 1000];
});

// Letters are valid identifiers (Prettier leaves them unquoted); space is not.
const key = (ch) => (/^\p{L}$/u.test(ch) ? ch : `'${ch}'`);
const body = `// Generated by scripts/build-sky-label-metrics.mjs — do not edit.
// EB Garamond Regular advance widths in em (${font.unitsPerEm} units per em),
// for every character of the uppercased constellation names plus A–Z.
export const LABEL_ADVANCE_EM: Readonly<Record<string, number>> = {
${entries.map(([ch, em]) => `  ${key(ch)}: ${em},`).join('\n')}
};
`;
writeFileSync('app/lib/sky/labelMetrics.ts', body);
console.log(`label metrics: ${entries.length} characters`);
/* eslint-enable no-console */
